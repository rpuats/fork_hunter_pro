    @classmethod
    def get_key(cls, home_team: str, away_team: str) -> str:
        """Получить нормализованный ключ для сопоставления событий."""
        home = cls.normalize(home_team)
        away = cls.normalize(away_team)
        
        # Сортировка для согласованности
        if home > away:
            home, away = away, home
        
        return f"{home}|{away}"
    
    @classmethod
    def are_same_match(cls, team1a: str, team1b: str, team2a: str, team2b: str) -> bool:
        """Проверяет, являются ли два матча одинаковыми."""
        key1 = cls.get_key(team1a, team1b)
        key2 = cls.get_key(team2a, team2b)
        return key1 == key2


