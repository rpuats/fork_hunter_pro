    # Регулярное выражение для кириллицы
    CYRILLIC_PATTERN = re.compile(r'[а-яёА-ЯЁ]')
    
    @classmethod
    @lru_cache(maxsize=10000)
    def normalize(cls, team_name: str) -> str:
        """
        Нормализует название команды.
        
        Args:
            team_name: Название команды (может быть на любом языке)
            
        Returns:
            Нормализованное название на кириллице (нижний регистр)
        """
        if not team_name:
            return ''
        
        # Приведение к нижнему регистру
        name = str(team_name).lower().strip()
        
        # Удаление кавычек и скобок
        name = re.sub(r'["\'\[\]\(\)]', '', name)
        
        # Удаление акцентов (диакритики)
        name = cls._remove_accents(name)
        
        # Удаление артиклей в начале
        name = re.sub(r'^(fc|cf|sc|ac|as|ss|sv|tsv|rfk|rk|sk|gk|ok|fk|vf|ff|if|df|uf)\s+', '', name)
        
        # Удаление "II", "III", "U21", etc. в конце
        name = re.sub(r'\s*(ii|iii|iv|v|u21|u23|u19|u18|u17)$', '', name)
        
        # Замена дефисов и точек на пробелы
        name = re.sub(r'[-.]', ' ', name)
        
        # Удаление лишних пробелов
        name = re.sub(r'\s+', ' ', name).strip()
        
        # Проверка алиасов
        if name in cls.TEAM_ALIASES:
            return cls.TEAM_ALIASES[name]
        
        # Если есть транслитерация - транслитерируем обратно на кириллицу
        if cls.CYRILLIC_PATTERN.search(name):
            return name
        
        # Транслитерация
        return cls._transliterate(name)
    
    @classmethod
    def _remove_accents(cls, text: str) -> str:
        """Удаление акцентов и диакритики."""
        replacements = {
            'é': 'e', 'è': 'e', 'ê': 'e', 'ë': 'e',
            'á': 'a', 'à': 'a', 'â': 'a', 'ä': 'a', 'ã': 'a', 'å': 'a',
            'í': 'i', 'ì': 'i', 'î': 'i', 'ï': 'i',
            'ó': 'o', 'ò': 'o', 'ô': 'o', 'ö': 'o', 'õ': 'o', 'ø': 'o',
            'ú': 'u', 'ù': 'u', 'û': 'u', 'ü': 'u',
            'ý': 'y', 'ÿ': 'y',
            'ñ': 'n', 'ç': 'c',
            'ß': 'ss',
            'æ': 'ae', 'œ': 'oe',
        }
        for char, replacement in replacements.items():
            text = text.replace(char, replacement)
        return text
    
